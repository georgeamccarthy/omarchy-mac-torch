"""Build omarchy_mac_torch/_native.so (the C++ backend) against torch and the wgpu-native library that ships with wgpu-py.

usage: uv run tools/build_native.py [--no-validate] [-v]   (the checkout path must not contain spaces)

Steps: embed csrc/kernels/*.wgsl into csrc/kernels_gen.inc, compile csrc/*.cpp, copy the library next to the package,
record which torch it was built against, and compile every kernel once on the GPU so a WGSL error fails the build
instead of the first model that uses it (--no-validate skips that, e.g. on a machine without a GPU)."""
import json
import os
import pathlib
import shutil
import ctypes
import subprocess
import sys

import torch
import wgpu
from torch.utils.cpp_extension import load

root = pathlib.Path(__file__).resolve().parent.parent
pkg = root / "omarchy_mac_torch"
csrc = root / "csrc"

# ---- embed the kernels ----
kernels = sorted((csrc / "kernels").glob("*.wgsl"))
with open(csrc / "kernels_gen.inc", "w") as f:
    f.write("// generated by tools/build_native.py from csrc/kernels/*.wgsl: do not edit\n")
    for k in kernels:
        src = k.read_text()
        assert ")OMTWGSL" not in src
        f.write(f'{{"{k.stem}", R"OMTWGSL({src})OMTWGSL"}},\n')

# ---- compile ----
res = pathlib.Path(wgpu.__file__).parent / "resources"
lib = res / "libwgpu_native-release.so"
shutil.copy(lib, pkg / lib.name)
build = pkg / "_build_native"
build.mkdir(exist_ok=True)
shutil.copy(lib, build / lib.name)  # so the extension imports from the build dir too
ctypes.CDLL(str(pkg / lib.name), mode=ctypes.RTLD_GLOBAL)  # load() imports the module once built
sources = sorted(str(p) for p in csrc.glob("*.cpp"))
os.environ.setdefault("MAX_JOBS", str(os.cpu_count() or 4))
load(name="_native", sources=sources, extra_include_paths=[str(res), str(csrc)],
     extra_cflags=["-O2", "-std=c++20", "-fvisibility=default"],
     extra_ldflags=[f"-L{pkg}", "-l:libwgpu_native-release.so", f"-Wl,-rpath,{pkg}"],
     build_directory=str(build), verbose="-v" in sys.argv)
for f in build.glob("_native*.so"):
    shutil.copy(f, pkg / f.name)

# ---- record the build, so import can refuse a mismatched torch with a clear message ----
info = {"torch": torch.__version__, "wgpu_native": wgpu.__version__, "kernels": len(kernels)}
(pkg / "_build_info.json").write_text(json.dumps(info, indent=1) + "\n")
print("built", [p.name for p in pkg.glob("_native*.so")], info)

# ---- compile every kernel on the GPU ----
if "--no-validate" not in sys.argv:
    code = ("import omarchy_mac_torch.native as n, sys; bad = n.validate_kernels(); "
            "print('\\n'.join(bad) or 'all kernels compile'); sys.exit(1 if bad else 0)")
    sys.exit(subprocess.call([sys.executable, "-c", code], cwd=root))
